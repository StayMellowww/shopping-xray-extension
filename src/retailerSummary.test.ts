import { describe, expect, it } from 'vitest';
import { extractRetailerSummary } from './retailerSummary';

const page = (html: string) => new DOMParser().parseFromString(html, 'text/html');

describe('retailer generated summary', () => {
  it('reads a bounded Amazon Customers say paragraph', () => {
    const doc = page('<section><h3>Customers say</h3><p>Customers appreciate the speed and easy installation, although some mention reliability problems over time.</p></section>');
    expect(extractRetailerSummary(doc, 'amazon')?.text).toContain('reliability problems');
  });

  it('reads Best Buy summary without the AI attribution sentence', () => {
    const doc = page('<section><h2>Customers are saying</h2><p>Customers are impressed with the overall performance and appreciate the straightforward setup process.</p><p>Generated by AI based on customer reviews.</p></section>');
    expect(extractRetailerSummary(doc, 'bestbuy')).toMatchObject({ source: 'Best Buy', text: 'Customers are impressed with the overall performance and appreciate the straightforward setup process.' });
  });

  it('accepts a short summary in a div next to the heading', () => {
    const doc = page('<section><h2>Customers are saying</h2><div>Customers appreciate the easy installation and fast performance of the memory.</div></section>');
    expect(extractRetailerSummary(doc, 'bestbuy')?.text).toContain('fast performance');
  });
});
