import type { Store } from './model';

export interface RetailerSummary { source: 'Amazon' | 'Best Buy'; text: string }

function clean(value: string): string {
  return value.replace(/Generated by AI based on customer reviews\.?/gi, '').replace(/\s+/g, ' ').trim();
}

export function extractRetailerSummary(doc: Document, store: Store): RetailerSummary | undefined {
  if (store === 'ebay') return undefined;
  const heading = [...doc.querySelectorAll('h2, h3, h4, [role="heading"]')].find(node =>
    store === 'amazon' ? /^customers say\s*:?$/i.test(node.textContent?.trim() || '') : /^customers are saying\s*:?$/i.test(node.textContent?.trim() || ''));
  const containers = [heading?.nextElementSibling, heading?.parentElement?.nextElementSibling, heading?.parentElement, doc.querySelector('#cr-insights-customer-reviews')].filter((node): node is Element => !!node);
  for (const container of containers) {
    const candidates = [...container.querySelectorAll('p, [data-hook="review-summary"]')];
    if (container.matches('p')) candidates.unshift(container);
    if (!candidates.length && container !== heading?.parentElement) candidates.push(container);
    for (const candidate of candidates) {
      const value = clean(candidate.textContent || '');
      if (value.length >= 45 && value.length <= 800 && !/^customers (?:say|are saying)/i.test(value)) {
        return { source: store === 'amazon' ? 'Amazon' : 'Best Buy', text: value };
      }
    }
  }
  return undefined;
}
